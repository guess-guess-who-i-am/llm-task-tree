import test from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdtemp,mkdir,writeFile,readFile,rm} from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import {createRequire} from 'node:module';
import {createTaskTreeAgentTools} from './task-tree-agent-tools.js';
import {starterTreeMarkdown} from './tree-registry.js';

test('agent creates and registers independent trees, links subtrees, and open UI discovers changes', {timeout:60000}, async t => {
  const root = await mkdtemp(path.join(os.tmpdir(),'tree-catalog-http-'));
  const main = starterTreeMarkdown({title:'项目目标',role:'method'});
  await writeFile(path.join(root,'task-tree.md'),main);
  const child = spawn(process.execPath,['server.js'],{env:{...process.env,TASK_TREE_PROJECT_ROOT:root,PORT:'0',TASK_TREE_NO_OPEN:'1'},stdio:['ignore','pipe','pipe']});
  let log = '';
  const base = await new Promise((resolve,reject)=>{
    const timer=setTimeout(()=>reject(new Error('startup: '+log)),15000);
    child.stdout.on('data',data=>{log+=data;const url=log.match(/running at (http:\/\/127\.0\.0\.1:\d+)/)?.[1];if(url){clearTimeout(timer);resolve(url);}});
    child.stderr.on('data',data=>log+=data);child.once('error',reject);
  });
  t.after(async()=>{child.kill();await new Promise(resolve=>child.once('exit',resolve));await rm(root,{recursive:true,force:true});});
  const bridge = await createTaskTreeAgentTools({cwd:root,environment:{TASK_TREE_CONTEXT_TREE_FILE:'task-tree.md',TASK_TREE_QUALITY_MODE:'advisory'}});
  t.after(()=>bridge.close());
  const definition = bridge.tools.find(t=>t.function.name==='task_tree_registry');
  assert.ok(definition,'every isolated/shared runtime must expose tree creation/registration');
  assert.match(definition.function.description,/子树|父节点/);
  const created = await bridge.call('task_tree_registry',{action:'create',id:'people',title:'人物树',role:'method',markdown:starterTreeMarkdown({title:'人物目标',role:'method'})});
  assert.equal(created.treeId,'people');assert.equal(created.url,'/?tree=people');
  assert.equal((await bridge.call('task_tree_registry',{action:'list'})).trees.length,2);
  assert.match((await bridge.call('task_tree_read',{treeId:'people'})).markdown,/人物目标/);
  assert.equal((await bridge.call('task_tree_node',{treeId:'people',nodeId:'ROOT'})).title,'人物目标');
  const patched=await bridge.call('task_tree_write',{treeId:'people',nodeId:'ROOT',fields:{CurrentResult:'新树可独立执行'},reason:'接入验证'});
  assert.equal(patched.ok,true);
  assert.match(await readFile(path.join(root,'trees/people.md'),'utf8'),/新树可独立执行/);
  assert.equal(await readFile(path.join(root,'task-tree.md'),'utf8'),main,'new tree operations must not edit original tree');
  const folded='# LLM Task Graph Subtree\n> Fold root: ROOT\n## ROOT - 人物目标\n## P1 - 人物资料\n- Problem: 记录哪些资料？\n# GraphState\n- Current: ROOT\n- Next: P1\n# Edges\n## EP - 资料\n- Endpoints: ROOT, P1\n';
  const fold=await bridge.call('task_tree_subtree',{treeId:'people',action:'write',path:'subtrees/people-detail.md',foldRoot:'ROOT',markdown:folded,reason:'接入人物子树'});
  assert.equal(fold.ok,true);
  assert.match(await readFile(path.join(root,'trees/people.md'),'utf8'),/SubtreeFile: subtrees\/people-detail.md/);
  assert.equal((await bridge.call('task_tree_node',{treeId:'people',nodeId:'P1'})).title,'人物资料');
  assert.equal(await readFile(path.join(root,'task-tree.md'),'utf8'),main);
  assert.equal((await bridge.call('task_tree_registry',{action:'list'})).activeMethod,'method');
  await Promise.all(Array.from({length:5},(_,i)=>bridge.call('task_tree_registry',{action:'create',id:`parallel-${i}`,title:`并发树${i}`})));
  assert.equal((await bridge.call('task_tree_registry',{action:'list'})).trees.length,7);
  await assert.rejects(()=>bridge.call('task_tree_registry',{action:'register',id:'missing',title:'不存在',path:'trees/missing.md'}),/不存在/);

  const {chromium} = createRequire(import.meta.url)('../prototype/swimlane-view/node_modules/playwright');
  const browser=await chromium.launch({headless:true});t.after(()=>browser.close());
  const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base);await page.waitForFunction(()=>window.taskTreeBoot?.state==='ready');
  if(await page.locator('#projectOverviewDialog').evaluate(e=>e.open))await page.locator('#projectOverviewClose').click();
  assert.equal(await page.locator('#treeSelect').inputValue(),'method');
  await mkdir(path.join(root,'trees'),{recursive:true});
  await writeFile(path.join(root,'trees/new-visible.md'),starterTreeMarkdown({title:'后台新建的树',role:'reference'}));
  await page.waitForFunction(()=>!!document.querySelector('#treeSelect option[value="new-visible"]'),{},{timeout:12000});
  assert.equal(await page.locator('#treeSelect').inputValue(),'method','background discovery preserves current tree');
  await page.locator('#treeSelect').selectOption('new-visible');
  await page.waitForFunction(()=>new URL(location.href).searchParams.get('tree')==='new-visible'&&document.querySelector('#graphCanvas')?.textContent.includes('后台新建的树'));
  const registered=await bridge.call('task_tree_registry',{action:'register',id:'new-visible',title:'正式树名',path:'trees/new-visible.md',role:'method'});
  assert.equal(registered.tree.title,'正式树名');
  await page.waitForFunction(()=>document.querySelector('#treeSelect option[value="new-visible"]')?.textContent.includes('正式树名'),{},{timeout:12000});
  assert.deepEqual(errors,[]);
});
