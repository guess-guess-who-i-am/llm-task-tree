test('final review records evidence for its explicit folded node without flow or a main-tree diff', async () => {
  const root=await mkdtemp(path.join(os.tmpdir(),'review-node-maintenance-'));
  await mkdir(path.join(root,'subtrees'));
  await writeFile(path.join(root,'task-tree.md'),tree);
  await writeFile(path.join(root,'subtrees/branch.md'),tree.replaceAll('ROOT','N9'));
  await writeFile(path.join(root,'task-trees.json'),JSON.stringify({activeMethod:'method',trees:[{id:'method',role:'method',path:'task-tree.md',flowEnabled:false}]}));
  const review={verdict:'pass',reason:'已修复并验证',evidence:['实际返回42']};
  const repair=await repairTurnMaintenance({projectRoot:root,changedFiles:['src/result.js','subtrees/branch.md'],executionNodeId:'N9',completionReview:review});
  assert.ok(repair.repairs.some(r=>r.code==='STEP_EVIDENCE_CREATED'));
  const step=JSON.parse(await readFile(path.join(root,'scripts/steps/N9/latest/step.json'),'utf8'));
  assert.equal(step.nodeId,'N9');
  assert.deepEqual(step.substeps.at(-1).completionReview,review);
  const status=await auditTurnMaintenance({projectRoot:root,changedFiles:repair.changedFiles});
  assert.ok(!status.issues.some(i=>i.code==='STEP_EVIDENCE_MISSING'));
  assert.ok(status.issues.some(i=>i.code==='TREE_NOT_UPDATED'),'recording evidence alone must not bypass tree maintenance');
  const scopedStatus=await auditTurnMaintenance({projectRoot:root,changedFiles:repair.changedFiles,executionNodeId:'N9',completionReview:review});
  assert.equal(scopedStatus.ok,true,JSON.stringify(scopedStatus.issues));
});

test('known review node resolves ambiguous main-tree changes and preserves a failed verdict', async () => {
  const root=await mkdtemp(path.join(os.tmpdir(),'review-ambiguous-maintenance-'));
  const before=tree.replace('# GraphState','## N1 - 实现\n- CurrentResult: 未完成\n\n# GraphState');
  await writeFile(path.join(root,'task-tree.md'),before.replace('子树已建立，实际行动尚待推进。','目标尚未完成').replace('- CurrentResult: 未完成','- CurrentResult: 验收失败'));
  const review={verdict:'failed',reason:'实际结果错误',evidence:['断言失败'],rootCause:'接口未实现'};
  const repair=await repairTurnMaintenance({projectRoot:root,previousTreeMarkdown:before,changedFiles:['src/result.js','task-tree.md'],executionNodeId:'N1',completionReview:review});
  assert.ok(repair.repairs.some(r=>r.code==='STEP_EVIDENCE_CREATED'));
  const step=JSON.parse(await readFile(path.join(root,'scripts/steps/N1/latest/step.json'),'utf8'));
  assert.equal(step.substeps.at(-1).completionReview.verdict,'failed');
  assert.match(await readFile(path.join(root,'scripts/steps/N1/latest/report.zh.md'),'utf8'),/failed/);
});

test('host review receipt includes all files and refreshes even when another node has evidence',async()=>{
  const root=await mkdtemp(path.join(os.tmpdir(),'review-all-files-'));
  await writeFile(path.join(root,'task-tree.md'),tree);
  const files=Array.from({length:25},(_,i)=>`src/file-${i}.js`);
  const args={projectRoot:root,changedFiles:[...files,'scripts/steps/OTHER/latest/step.json'],executionNodeId:'ROOT',completionReview:{verdict:'pass',reason:'实际通过',evidence:['实际验证']}};
  const first=await repairTurnMaintenance(args);
  assert.ok(first.repairs.some(r=>r.code==='STEP_EVIDENCE_CREATED'));
  const second=await repairTurnMaintenance({...args,changedFiles:[...args.changedFiles,...first.changedFiles]});
  assert.ok(second.repairs.some(r=>r.code==='STEP_EVIDENCE_CREATED'));
  const step=JSON.parse(await readFile(path.join(root,'scripts/steps/ROOT/latest/step.json'),'utf8'));
  assert.equal(step.substeps.filter(s=>s.autoGenerated).length,1);
  assert.equal(step.substeps.at(-1).outputs.length,25);
});

