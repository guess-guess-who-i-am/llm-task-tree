const tree='# LLM Task Graph\n\n## ROOT - 验证目标\n- Problem: 如何展开子树？\n- CurrentResult: 子树已建立，实际行动尚待推进。\n\n# GraphState\n- Current: ROOT\n- Next: ROOT\n\n# Edges\n';
test('a persisted final tree-consistency receipt closes a factual correction without a no-op tree write',async()=>{
  const root=await mkdtemp(path.join(os.tmpdir(),'review-tree-consistency-'));
  await writeFile(path.join(root,'task-tree.md'),tree);
  const review={verdict:'pass',reason:'仅修正论文获取方式，节点能力和缺口不变',evidence:['实际文献与方案一致'],treeState:{status:'consistent',reason:'ROOT当前结论与剩余缺口仍准确'}};
  const args={projectRoot:root,changedFiles:['knowledge-base/schema.md'],executionNodeId:'ROOT',completionReview:review};
  const missing=await auditTurnMaintenance(args);
  assert.ok(missing.issues.some(i=>i.code==='TREE_NOT_UPDATED'),'model declaration without a persisted receipt is insufficient');
  const repair=await repairTurnMaintenance(args);
  const audited=await auditTurnMaintenance({...args,changedFiles:repair.changedFiles});
  assert.equal(audited.ok,true,JSON.stringify(audited.issues));
  assert.equal(await readFile(path.join(root,'task-tree.md'),'utf8'),tree,'must not touch current tree merely to satisfy mtime');
  await writeFile(path.join(root,'task-tree.md'),tree.replace('实际行动尚待推进','实际行动已完成'));
  const stale=await auditTurnMaintenance({...args,changedFiles:repair.changedFiles});
  assert.ok(stale.issues.some(i=>i.code==='TREE_NOT_UPDATED'),'receipt cannot attest a subsequently changed tree');
});

